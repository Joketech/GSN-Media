import {readFile,writeFile} from 'node:fs/promises';
// Deliberate spatial systems, not colour variants. Rectangles use canvas percentages.
// Each pairing of image stage and copy hierarchy occurs once in this collection.
const stages=[
 ['Editorial window',[4,30,92,56],'0','none'],
 ['Arched portrait',[8,29,84,60],'45% 45% 0 0','none'],
 ['Left image / right note',[0,29,72,61],'0 28% 0 0','none'],
 ['Right image / left note',[28,29,72,61],'28% 0 0 0','none'],
 ['Inset gallery',[13,32,74,53],'2%','double'],
 ['Full studio',[0,27,100,64],'0','none'],
 ['Floating print',[8,32,84,54],'0','paper'],
 ['Rounded capsule',[10,28,80,61],'40%','none'],
 ['Open left edge',[0,32,88,55],'0 30% 0 0','line'],
 ['Open right edge',[12,32,88,55],'30% 0 0 0','line'],
 ['Centre medallion',[6,31,88,55],'50%','none'],
 ['Landscape photograph',[0,32,100,49],'0','none'],
 ['Tall narrow stage',[17,28,66,64],'1%','line'],
 ['Lower showroom',[0,39,100,48],'0','none'],
 ['Upper gallery',[7,27,86,49],'0','line'],
 ['Angled print',[10,33,80,52],'1%','tilt'],
 ['Asymmetric arch',[5,29,90,60],'32% 0 32% 0','none'],
 ['Rounded display',[4,31,92,55],'10%','inset'],
 ['Narrow editorial',[4,28,76,61],'0','paper'],
 ['Wide display',[0,30,100,57],'8% 8% 0 0','rule'],
];
// Substantial hierarchy differences: headline alignment, text columns, footer shape,
// image outline, edge labels and caption location. None depend on the palette.
const treatments=[
 {name:'Serif journal',font:'Georgia',align:'left',weight:400,header:0,caption:'below',footer:'rule',mark:'line'},
 {name:'Centred statement',font:'Arial',align:'center',weight:800,header:1,caption:'below',footer:'pill',mark:'disc'},
 {name:'Magazine title',font:'Georgia',align:'right',weight:400,header:2,caption:'below',footer:'split',mark:'corner'},
 {name:'Utility label',font:'monospace',align:'left',weight:700,header:3,caption:'below',footer:'outline',mark:'cross'},
 {name:'Italic editorial',font:'Georgia',align:'center',weight:500,header:4,caption:'below',footer:'tab',mark:'arc'},
 {name:'Oversized headline',font:'Arial',align:'left',weight:900,header:5,caption:'below',footer:'bar',mark:'square'},
 {name:'Right-aligned feature',font:'Arial',align:'right',weight:700,header:6,caption:'below',footer:'rule',mark:'bracket'},
 {name:'Stacked masthead',font:'Georgia',align:'left',weight:700,header:7,caption:'below',footer:'pill',mark:'ring'},
 {name:'Modern catalogue',font:'Arial',align:'center',weight:500,header:8,caption:'below',footer:'split',mark:'dash'},
 {name:'Compact poster',font:'monospace',align:'right',weight:700,header:9,caption:'below',footer:'tab',mark:'diamond'},
];
const rows=JSON.parse(await readFile(new URL('manifest.json',import.meta.url),'utf8'));
// Product order is curated within each category so neighbouring products do not
// inherit the same spatial stage. A Latin assignment makes all 200 pairs unique.
const order=[0,5,3,13,15,2,12,11,8,14];
const records=rows.map(d=>{
 const group=Math.floor(d.id/10),slot=d.id%10,index=(order[slot]+group)%20;
 const [stage,photo,radius,frame]=stages[index],t=treatments[slot];
 const hookY=index===13?11:10.5,hookH=index===13?22:index===14?14:16;
 let description=[7,86,86,6];
 if(index===2)description=[74,36,22,42];
 if(index===3)description=[4,36,22,42];
 if(index===14)description=[7,78,86,10];
 if(index===18)description=[82,34,15,49];
 if(index===11)description=[7,82,86,9];
 const hook=[slot===2?10:slot===5?5:7,hookY,slot===2?80:slot===5?90:86,hookH];
 const footer=t.footer==='split'?[7,94,63,4]:t.footer==='tab'?[22,94,71,4]:[7,94,86,4];
 return {id:d.id,name:`${d.product} / ${stage} / ${t.name}`,stage,typography:t.name,
  photo,hook,description,footer,radius,frame,font:t.font,align:t.align,weight:t.weight,header:t.header,footerStyle:t.footer,mark:t.mark,
  italic:slot===4,reference:[0,8,10].includes(d.id),
  geometryKey:JSON.stringify([photo,hook,description,footer,radius,frame,t.font,t.align,t.weight,t.header,t.footer,t.mark])};
});
if(new Set(records.map(r=>r.geometryKey)).size!==200)throw Error('A repeated composition must not be counted.');
await writeFile(new URL('cover-designs.json',import.meta.url),JSON.stringify(records,null,2)+'\n');
await writeFile(new URL('cover-designs.js',import.meta.url),'// Generated by build-covers.mjs; no product images or accepted starters are overwritten.\nconst UGC_DESIGNS='+JSON.stringify(records)+';\n');
console.log('200 colour-independent composition records; original approved covers retained.');
